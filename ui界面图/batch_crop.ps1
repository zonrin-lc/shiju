foreach ($job in $jobs) {
  $srcPath = Join-Path $srcDir $job.file
  $outDir = Join-Path $baseOut $job.out
  New-Item -ItemType Directory -Force $outDir | Out-Null
  $img = [System.Drawing.Image]::FromFile($srcPath)
  foreach ($c in $job.crops) {
    $name = $c[0]; $x = $c[1]; $y = $c[2]; $w = $c[3]; $h = $c[4]
    # clamp
    if ($x + $w -gt $img.Width) { $w = $img.Width - $x }
    if ($y + $h -gt $img.Height) { $h = $img.Height - $y }
    if ($w -le 0 -or $h -le 0) { continue }
    $rect = New-Object System.Drawing.Rectangle($x, $y, $w, $h)
    $bmp = New-Object System.Drawing.Bitmap($w, $h)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.DrawImage($img, (New-Object System.Drawing.Rectangle(0,0,$w,$h)), $rect, [System.Drawing.GraphicsUnit]::Pixel)
    $bmp.Save("$outDir\$name.png", [System.Drawing.Imaging.ImageFormat]::Png)
    $g.Dispose(); $bmp.Dispose()
  }
  $img.Dispose()
  Write-Output "cropped: $($job.out)"
}
